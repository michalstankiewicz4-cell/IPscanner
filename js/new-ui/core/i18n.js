  function storageGet(key) {
    var storage = getStorageAdapter();
    if (storage && typeof storage.getItem === "function") {
      return storage.getItem(key);
    }
    try {
      return localStorage.getItem(key);
    } catch (_) {
      return null;
    }
  }

